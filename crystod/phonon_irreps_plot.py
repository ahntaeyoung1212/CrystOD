"""Phonon dispersion with ISO-IR irrep labels (``crystod-phonon --irreps``).

The phonopy bands along the seekpath k path of the primitive cell (or the
``--band`` path) and, at the special points of the path, the ISO-IR label of
every degenerate level as ``crystod-phonon --irreps`` writes it to
``phonon_irreps.yaml`` (``GM4-(3)``; a one-dimensional irrep without its
``(1)``, a set holding several irreps as ``X1+ + X2+``).  Every point is
labeled once, at its last place on the path that is not a break (``X|R``);
labels of close levels are moved apart and tied to their level by a leader
line, and levels below the imaginary threshold (``--threshold``, default
-0.1 THz) are drawn in red.

The labels are read at the vertex itself (through the tabulated arm of its
star, whose spectrum is the same), so they sit on the drawn bands whatever
the path.  Conventions: THz, imaginary frequencies negative; distances in
phonopy's reciprocal metric of the primitive cell.
"""

from __future__ import annotations

import re
import warnings
from dataclasses import dataclass, field

import numpy as np

CURVE = "#184f95"
IMAGINARY = "#e34948"
FIG_W, FIG_H = 16.0, 12.0  # cm
MARGIN_L, MARGIN_R, MARGIN_T, MARGIN_B = 1.7, 0.4, 1.0, 1.4  # cm
LABEL_FONT = 6.0  # pt
LABEL_GAP = 1.2  # line pitch of stacked labels, in units of the font size
LEADER = 10.0  # pt, horizontal length of a leader line
CITATION = (
    "irrep labels: ISO-IR (H. T. Stokes, B. J. Campbell & R. Cordes, Acta Cryst. A69, 388 "
    "(2013)) -- generated by CrystOD (crystod-phonon --irreps)"
)
_ISO_TO_SEEKPATH = {"GM": "GAMMA", "DT": "DELTA", "SM": "SIGMA", "LD": "LAMBDA"}


@dataclass
class LabeledPoint:
    """The levels at one labeled vertex of the path."""

    name: str
    x: float
    side: str  # "right" or "left" of the vertex
    levels: list = field(default_factory=list)  # (frequency in THz, text)
    q: list = field(default_factory=list)  # fractional q of the vertex (primitive reciprocal basis)


@dataclass
class Dispersion:
    """Everything the figure draws: bands per leg, ticks and the labeled points."""

    distances: list
    frequencies: list
    ticks: list
    tick_labels: list
    points: list
    path_string: str
    n_qpoints: int
    notes: list


def _set_text(labels) -> str:
    """The text of one degenerate set: ``GM4-(3)``, ``X3-`` for a 1-dim irrep,
    ``X1+ + X2+`` for a set holding several irreps, ``?`` when unlabeled."""
    if not labels:
        return "?"
    return " + ".join(re.sub(r"\(1\)$", "", str(label)) for label in labels)


def _display_name(name: str) -> str:
    return "GM" if name == "GAMMA" else name


def _path_string(names) -> str:
    """``GM-X-M-GM-R-X | R-M``, the form of ``k_path`` in ``phonon_irreps_all.yaml``."""
    return " | ".join("-".join(_display_name(n) or "?" for n in part) for part in names)


def _formula_mathtext(symbols) -> str:
    """``SrTiO$_{3}$`` from the atom symbols of a cell, in their order of appearance."""
    from math import gcd

    counts: dict = {}
    for symbol in symbols:
        counts[symbol] = counts.get(symbol, 0) + 1
    divisor = 0
    for n in counts.values():
        divisor = gcd(divisor, n)
    return "".join(
        f"{s}$_{{{n // divisor}}}$" if n // divisor != 1 else s for s, n in counts.items()
    )


def _space_group_mathtext(symbol: str) -> str:
    """``Pm-3m`` -> Pm(bar 3)m and ``P4_2/mnm`` -> P4(sub 2)/mnm, letters italic (mathtext)."""
    parts = []
    for token in re.findall(r"-\d|_\d|\d|[A-Za-z]+|.", symbol):
        if token.startswith("-"):
            parts.append(r"\bar{%s}" % token[1])
        elif token.startswith("_"):
            parts.append("_{%s}" % token[1])
        elif token.isalpha():
            parts.append(r"\mathit{%s}" % token)
        else:
            parts.append(token)
    return "$" + "".join(parts) + "$"


def _spread(y, gap: float, lo: float, hi: float) -> np.ndarray:
    """Positions closest (least squares) to the ascending ``y``, at least ``gap``
    apart and within ``[lo, hi]`` (as far as the room allows).

    With ``z_i = p_i - i gap`` the spacing condition is ``z`` non-decreasing, so
    the closest ``z`` is the isotonic regression of ``y_i - i gap`` (pool
    adjacent violators), clipped to the room, which keeps it optimal."""
    n = len(y)
    if n == 0:
        return np.zeros(0)
    offsets = gap * np.arange(n)
    blocks: list = []  # [sum, count] of pooled values
    for value in np.asarray(y, dtype=float) - offsets:
        blocks.append([value, 1])
        while len(blocks) > 1 and blocks[-2][0] / blocks[-2][1] > blocks[-1][0] / blocks[-1][1]:
            total, count = blocks.pop()
            blocks[-1][0] += total
            blocks[-1][1] += count
    fit = np.concatenate([np.full(count, total / count) for total, count in blocks])
    upper = max(lo, hi - offsets[-1])
    return np.clip(fit, lo, upper) + offsets


def _path(phonon, band, band_labels, tolerance):
    """``(segments, names, notes)`` of the k path: the ``--band`` path, its
    vertices named by ``band_labels`` or else by their ISO-IR k-vector type,
    or the seekpath path of the primitive cell, its points renamed where the
    frame of the labels gives another ISO-IR type (as ``--all-irreps`` does)."""
    from .brillouin_zone import get_seekpath_kpath, parse_manual_band
    from .isoir import get_isoir_kpoint_name
    from .phonon_irreps import _input_cell, _path_points_renamed_by_frame
    from .runtime_compat import get_symmetry_dataset

    primitive = phonon.primitive
    cell = (primitive.cell, primitive.scaled_positions, primitive.numbers)
    notes = []
    if band:
        segments = parse_manual_band(band)
        if band_labels:
            flat = band_labels.split()
            expected = sum(len(segment) for segment in segments)
            if len(flat) != expected:
                raise SystemExit(
                    f"ERROR: --band-labels needs {expected} labels for this --band path, "
                    f"but {len(flat)} were given."
                )
            names, cursor = [], 0
            for segment in segments:
                names.append(flat[cursor : cursor + len(segment)])
                cursor += len(segment)
        else:
            number = get_symmetry_dataset(phonon.primitive_symmetry)["number"]
            names = [
                [
                    get_isoir_kpoint_name(
                        number, cell, phonon.primitive_symmetry.tolerance, list(k),
                        input_cell=_input_cell(phonon),
                    ) or ""
                    for k in segment
                ]
                for segment in segments
            ]
        return segments, names, notes

    segments, names, lattice, _, number = get_seekpath_kpath(primitive, tolerance)
    if not np.allclose(np.array(primitive.cell), lattice, atol=1e-4):
        notes.append(
            "the input cell differs from the seekpath standardized primitive cell; the "
            "k-path coordinates refer to the standardized cell (give --band for a path "
            "in the primitive cell of the input)"
        )
    coords = {n: k for segment, ns in zip(segments, names) for n, k in zip(ns, segment)}
    renamed = _path_points_renamed_by_frame(phonon, number, cell, coords)
    names = [[renamed.get(n, _display_name(n)) for n in ns] for ns in names]
    return segments, names, notes


def _tick_text(name: str) -> str:
    """Tick label of a vertex name (``GM`` -> Gamma, ``X_1`` -> X with subscript 1)."""
    from .phonon_fatband import _prettify_label_mpl

    stem, sep, subscript = name.partition("_")
    return _prettify_label_mpl(_ISO_TO_SEEKPATH.get(stem, stem) + sep + subscript)


def _levels_at(phonon, q, labelling, degeneracy_tolerance):
    """``[(frequency, text), ...]`` of the degenerate sets at q, labeled at the
    tabulated arm of the star of q when there is one (the spectra of star arms
    coincide band by band), as ``crystod.phonon.label_phonon_modes`` does."""
    from .phonon_irreps import find_star_representative, get_irrep_labels

    irt_table, prim_mat, q_names, q_list, rotations = labelling
    label_q = list(q)
    representative = find_star_representative(q, rotations, q_names, q_list)
    if representative is not None:
        label_q = list(representative[1])
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="No irreps at")
        labels, band_indices, frequencies = get_irrep_labels(
            q=label_q, phonon=phonon, irt_table=irt_table, prim_mat=prim_mat,
            degeneracy_tolerance=degeneracy_tolerance,
        )
    return [
        (float(frequencies[indices[0]]), _set_text(labels[i]))
        for i, indices in enumerate(band_indices)
    ]


def compute_dispersion(
    phonon,
    irt_table,
    prim_mat,
    *,
    degeneracy_tolerance: float = 1e-3,
    band: str | None = None,
    band_labels: str | None = None,
    npoints: int | None = None,
    tolerance: float = 1e-5,
) -> Dispersion:
    """The bands along the path and the ISO-IR labels of its special points.

    Args:
        phonon: The ``phonopy.Phonopy`` object of ``crystod-phonon --irreps``
            (``primitive_matrix="auto"``, force constants available).
        irt_table, prim_mat: The ISO-IR table of the space group and the
            centring matrix, as in :func:`crystod.phonon_irreps.get_irrep_labels`.
        degeneracy_tolerance: THz within which bands form one set (``--tolerance``).
        band, band_labels: A manual path (``--band``, primitive reciprocal
            basis) and its vertex names (``--band-labels``); default seekpath.
        npoints: q points per leg (default 51).
        tolerance: Symmetry tolerance of seekpath.
    """
    from phonopy.phonon.band_structure import get_band_qpoints_and_path_connections

    from .phonon_irreps import get_irt_special_points
    from .runtime_compat import get_symmetry_dataset

    segments, names, notes = _path(phonon, band, band_labels, tolerance)
    band_paths = [np.array(segment, dtype=float) for segment in segments]
    qpoints, connections = get_band_qpoints_and_path_connections(
        band_paths, npoints=npoints or 51
    )
    phonon.run_band_structure(
        qpoints, path_connections=connections, with_eigenvectors=False,
        is_band_connection=False,
    )
    result = phonon.get_band_structure_dict()
    distances = [np.array(d, dtype=float) for d in result["distances"]]
    frequencies = [np.array(f, dtype=float) for f in result["frequencies"]]

    # the vertices in path order: (x, q, name, at a break of the path)
    leg_names = [(ns[i], ns[i + 1]) for ns in names for i in range(len(ns) - 1)]
    vertices = []
    for i, (start, end) in enumerate(leg_names):
        if i == 0 or not connections[i - 1]:
            vertices.append((distances[i][0], qpoints[i][0], start, i > 0))
        last = i == len(leg_names) - 1
        vertices.append((distances[i][-1], qpoints[i][-1], end, not connections[i] and not last))

    ticks, tick_labels = [], []
    for x, _, name, _ in vertices:
        if ticks and abs(x - ticks[-1]) < 1e-10:
            left, right = tick_labels[-1], _tick_text(name)
            tick_labels[-1] = left if left == right else f"{left}|{right}"
        else:
            ticks.append(float(x))
            tick_labels.append(_tick_text(name))

    # every point once: its last place on the path that is not a break
    chosen: dict = {}
    for index, (x, q, name, at_break) in enumerate(vertices):
        key = tuple(np.round(np.asarray(q, dtype=float), 6))
        if key not in chosen or not at_break or vertices[chosen[key]][3]:
            chosen[key] = index

    q_names, q_list = get_irt_special_points(irt_table, prim_mat)
    rotations = get_symmetry_dataset(phonon.primitive_symmetry)["rotations"]
    labelling = (irt_table, prim_mat, q_names, q_list, rotations)
    x_end = float(distances[-1][-1])
    points = []
    for index in sorted(chosen.values()):
        x, q, name, _ = vertices[index]
        try:
            levels = _levels_at(phonon, q, labelling, degeneracy_tolerance)
        except Exception:
            point = name or "(" + ", ".join(f"{v:g}" for v in q) + ")"
            notes.append(f"no ISO-IR labels at {point}; drawn without labels")
            continue
        side = "left" if abs(float(x) - x_end) < 1e-10 else "right"
        point = LabeledPoint(
            _display_name(name), float(x), side, levels, [float(v) for v in q]
        )
        if points and abs(points[-1].x - point.x) < 1e-10:
            # both sides of a break (U|K of fcc): one set of labels when the two
            # spectra and labels agree (equivalent points), else one on each side
            same = len(points[-1].levels) == len(levels) and all(
                abs(a[0] - b[0]) < 1e-3 and a[1] == b[1]
                for a, b in zip(sorted(points[-1].levels), sorted(levels))
            )
            if same:
                points[-1].name += "|" + point.name
                continue
            points[-1].side = "left"
        points.append(point)

    return Dispersion(
        distances=distances,
        frequencies=frequencies,
        ticks=ticks,
        tick_labels=tick_labels,
        points=points,
        path_string=_path_string(names),
        n_qpoints=int(sum(len(q) for q in qpoints)),
        notes=notes,
    )


def draw_dispersion(
    data: Dispersion,
    output: str,
    *,
    title: str,
    threshold: float = -0.1,
    dpi: int = 300,
) -> None:
    """Draw ``data`` to ``output`` (format from the extension: pdf, png, svg, ...).

    Levels below ``threshold`` (THz) are drawn in red; computes nothing but
    the drawing."""
    from .phonon_unfold_plot import GRID, INK, INK2, PT_CM, _fit_font, _style, _text_width_pt

    plt = _style()
    fig = plt.figure(figsize=(FIG_W / 2.54, FIG_H / 2.54))
    ax_w, ax_h = FIG_W - MARGIN_L - MARGIN_R, FIG_H - MARGIN_T - MARGIN_B
    ax = fig.add_axes(
        [MARGIN_L / FIG_W, MARGIN_B / FIG_H, ax_w / FIG_W, ax_h / FIG_H]
    )
    ax_w_pt, ax_h_pt = ax_w / PT_CM, ax_h / PT_CM

    for x, f in zip(data.distances, data.frequencies):
        ax.plot(x, f, color=CURVE, lw=0.9, zorder=2)
    every = np.concatenate([f.ravel() for f in data.frequencies]
                           + [np.array([lv[0] for p in data.points for lv in p.levels])])
    low, high = min(0.0, float(every.min())), max(0.0, float(every.max()))
    pad = 0.05 * (high - low or 1.0)
    ylim = (low - pad, high + pad)
    x_min, x_max = float(data.distances[0][0]), float(data.distances[-1][-1])
    ax.set_xlim(x_min, x_max)
    ax.set_ylim(*ylim)
    ax.set_xticks(data.ticks)
    ax.set_xticklabels(data.tick_labels, fontsize=9)
    ax.tick_params(axis="y", labelsize=8)
    ax.set_ylabel("Frequency (THz)", fontsize=9)
    for tick in data.ticks[1:-1]:
        ax.axvline(tick, color=GRID, lw=0.6, zorder=0)
    ax.axhline(0.0, color=INK2, lw=0.5, ls=(0, (4, 3)), zorder=1)
    from matplotlib.ticker import AutoMinorLocator

    ax.yaxis.set_minor_locator(AutoMinorLocator())

    def to_pt(f):
        return (f - ylim[0]) / (ylim[1] - ylim[0]) * ax_h_pt

    gap = LABEL_GAP * LABEL_FONT
    for point in data.points:
        levels = sorted(point.levels)
        y_pt = np.array([to_pt(f) for f, _ in levels])
        placed = _spread(y_pt, gap, gap / 2, ax_h_pt - gap / 2)
        x_pt = (point.x - x_min) / (x_max - x_min) * ax_w_pt
        side = point.side
        widest = max(_text_width_pt(text, LABEL_FONT) for _, text in levels)
        if side == "right" and x_pt + LEADER + widest + 2 > ax_w_pt:
            side = "left"
        sign = 1.0 if side == "right" else -1.0
        for (f, text), y0, y1 in zip(levels, y_pt, placed):
            color = IMAGINARY if f < threshold else INK
            ax.plot([point.x], [f], "o", ms=2.6, color=color, zorder=4, clip_on=False)
            ax.annotate(
                text,
                xy=(point.x, f),
                xytext=(sign * LEADER, y1 - y0),
                textcoords="offset points",
                ha="left" if sign > 0 else "right",
                va="center",
                fontsize=LABEL_FONT,
                color=color,
                zorder=5,
                bbox=dict(boxstyle="square,pad=0.1", fc="white", ec="none", alpha=0.8),
                arrowprops=dict(
                    arrowstyle="-", lw=0.4, color=INK2, shrinkA=0, shrinkB=0,
                    relpos=(0.0, 0.5) if sign > 0 else (1.0, 0.5),
                ),
            )

    fig_w_pt = FIG_W / PT_CM
    size = _fit_font([title], 11.0, fig_w_pt - 20, 7.0)
    fig.text(0.5, 1 - 0.35 / FIG_H, title, fontsize=size, ha="center", va="top", color=INK)
    size = _fit_font([CITATION], 5.5, fig_w_pt - 20, 4.0)
    fig.text(0.5, 0.15 / FIG_H, CITATION, fontsize=size, ha="center", va="bottom", color=INK2)
    fig.savefig(output, dpi=dpi)
    plt.close(fig)


def plot_irreps_dispersion(
    phonon,
    irt_table,
    prim_mat,
    output: str,
    *,
    space_group: str,
    nac: bool = False,
    threshold: float = -0.1,
    **path_options,
) -> Dispersion:
    """:func:`compute_dispersion` and :func:`draw_dispersion` in one call;
    returns the computed data (the path and notes for the terminal)."""
    data = compute_dispersion(phonon, irt_table, prim_mat, **path_options)
    title = (
        f"{_formula_mathtext(phonon.primitive.symbols)} "
        f"({_space_group_mathtext(space_group)}) phonon dispersion with ISO-IR irrep labels"
    )
    if nac:
        title += " (NAC)"
        data.notes.append(
            "at GM the labels are those of the TO modes (phonopy applies no q direction "
            "at GM itself); the LO branches end there without labels"
        )
    draw_dispersion(data, output, title=title, threshold=threshold)
    return data
