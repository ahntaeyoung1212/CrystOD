#!/usr/bin/env python3
r"""VASP-style electronic band structure of a periodic solid with PySCF (PBC).

This example reproduces the two-step recipe that VASP uses for a band plot::

    step 1  self-consistent field on a regular Gamma-centred k-mesh
            (VASP: the weighted k-points of KPOINTS; symmetry-reduced to the
             irreducible wedge)
    step 2  non-self-consistent diagonalisation of the *converged* Kohn-Sham
            Hamiltonian on a high-symmetry k-path
            (VASP: the zero-weight k-points of KPOINTS)

In PySCF the second step is exactly ``mf.get_bands(kpts_band, dm_kpts=dm)``:
the converged density matrix from step 1 is kept fixed, the Fock matrix is
rebuilt at each requested k, and that matrix is diagonalised.  No new SCF is
performed, which is what "zero weight" means in VASP.

The high-symmetry path can come from three places:

* ``--kpoints BAND/KPOINTS``  read the zero-weight lines of a VASP KPOINTS file,
  so the PySCF path is *identical* to the VASP one (explicit or line mode);
* ``--path "GAMMA X M GAMMA R X | R M"``  labels resolved by seekpath;
* nothing at all, in which case the whole path is generated by seekpath.

Examples
--------
Band structure of ScF3 (this directory), roughly 15 min on a laptop::

    python pyscf_band_structure.py 221_PPOSCAR_ScF3 --kmesh 4 4 4 --npoints 21

Reproduce the SrTiO3 VASP reference in ``BAND/`` and overlay it::

    python pyscf_band_structure.py BAND/POSCAR --kmesh 4 4 4 \
        --kpoints BAND/KPOINTS --compare-vasp BAND

Element-projected fatbands (Mulliken weights, one PDF per element), plus a DOS
from the SCF mesh and the raw crystal orbitals for a later symmetry analysis::

    python pyscf_band_structure.py 221_PPOSCAR_ScF3 --kmesh 4 4 4 \
        --fatband --dos --save-mo

A one-minute smoke test, for checking a path or a plot before committing to a
real run (the minimal SZV basis is *not* accurate enough for a gap)::

    python pyscf_band_structure.py 221_PPOSCAR_ScF3 --basis gth-szv-molopt-sr \
        --ke-cutoff 80 --kmesh 2 2 2 --npoints 7

Outputs
-------
``<prefix>.pdf``       band plot (with the VASP overlay if one was given)
``<prefix>.dat``       gnuplot-style two-column blocks, one per band
``<prefix>.json``      every number the run produced, including the SCF mesh
``<prefix>_<El>.pdf``  element fatband        (``--fatband``)
``<prefix>_dos.pdf``   density of states      (``--dos``)
``<prefix>_mo.npz``    crystal orbitals + AO overlap  (``--save-mo``)

Notes on accuracy
-----------------
``--ke-cutoff`` is the PySCF analogue of VASP's ENCUT: it sets the FFT grid used
for the Coulomb and exchange-correlation integrals.  It is *not* a basis-set
cutoff -- the basis is the Gaussian set given by ``--basis``.  Absolute
eigenvalues therefore differ from VASP (different pseudopotentials, different
basis), but band dispersions, gaps and orbital characters are comparable once
both are aligned at the valence-band maximum, which is what ``--compare-vasp``
does.
"""

