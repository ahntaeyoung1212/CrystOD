def read_poscar(path: Path) -> tuple[np.ndarray, list[str], np.ndarray]:
    """Read a VASP-5 POSCAR/CONTCAR/PPOSCAR.

    Returns ``(lattice, symbols, fractional_positions)`` with the lattice in
    Angstrom and the lattice vectors as *rows*, matching both VASP and
    ``pyscf.pbc.gto.Cell.a``.
    """
    raw = [line for line in path.read_text().splitlines()]
    lines = [line.strip() for line in raw if line.strip()]
    if len(lines) < 8:
        raise SystemExit(f"ERROR: POSCAR is too short: {path}")

    scale = float(lines[1].split()[0])
    lattice = np.array([[float(x) for x in lines[i].split()[:3]] for i in (2, 3, 4)])
    if scale < 0:
        # VASP convention: a negative scale is the target cell volume.
        volume = abs(np.linalg.det(lattice))
        scale = (abs(scale) / volume) ** (1.0 / 3.0)
    lattice = lattice * scale

    symbols_line = lines[5].split()
    if all(token.lstrip("-").isdigit() for token in symbols_line):
        raise SystemExit(
            "ERROR: this example needs a VASP-5 POSCAR with an element-symbol line;\n"
            f"       '{path}' looks like VASP 4 (no symbols)."
        )
    counts = [int(x) for x in lines[6].split()]
    if len(symbols_line) != len(counts):
        raise SystemExit("ERROR: the element and count lines of the POSCAR have different lengths")

    index = 7
    if lines[index][0] in "sS":
        index += 1  # selective dynamics
    mode = lines[index][0].lower()
    if mode not in "dck":
        raise SystemExit("ERROR: could not find the Direct/Cartesian line of the POSCAR")
    index += 1

    natom = sum(counts)
    if len(lines) < index + natom:
        raise SystemExit(f"ERROR: POSCAR lists fewer than {natom} atomic positions")
    coords = np.array([[float(x) for x in lines[i].split()[:3]] for i in range(index, index + natom)])
    if mode == "d":
        frac = coords
    else:
        frac = (coords * scale) @ np.linalg.inv(lattice)

    symbols = [symbol for symbol, count in zip(symbols_line, counts) for _ in range(count)]
    return lattice, symbols, frac


