def element_color(symbol: str) -> tuple[float, float, float]:
    """VESTA colour of an element, darkened when it is too pale to see on white."""
    color = VESTA_COLORS.get(symbol, DEFAULT_COLOR)
    luminance = 0.299 * color[0] + 0.587 * color[1] + 0.114 * color[2]
    if luminance > 0.55:
        # Sc, Ti, Ag ... are almost white in VESTA and vanish on a white page;
        # keep the hue but scale the brightness into a visible range.
        color = tuple(component * 0.55 / luminance for component in color)
    return color


