def write_dat(path: Path, distances, energies_ev, header: str, zero: str):
    with path.open("w") as handle:
        handle.write(f"# {header}\n# distance(1/Angstrom)  energy(eV, referred to {zero})\n")
        for band in range(energies_ev.shape[1]):
            for distance, energy in zip(distances, energies_ev[:, band]):
                handle.write(f"{distance:14.8f} {energy:16.8f}\n")
            handle.write("\n")


def plot_bands(
    output: Path,
    distances,
    energies_ev,
    ticks,
    tick_labels,
    breaks_distance,
    title: str,
    energy_window,
    ylabel: str,
    fermi_ev=None,
    vasp=None,
    weights=None,
    color=DEFAULT_COLOR,
    weight_label=None,
):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figure, axis = plt.subplots(figsize=(5.0, 6.0))
    if vasp is not None:
        vasp_distance, vasp_energy = vasp
        for band in range(vasp_energy.shape[1]):
            axis.plot(
                vasp_distance,
                vasp_energy[:, band],
                color="0.55",
                linewidth=2.4,
                alpha=0.55,
                zorder=1,
                label="VASP (reference)" if band == 0 else None,
            )

    if weights is None:
        for band in range(energies_ev.shape[1]):
            axis.plot(
                distances,
                energies_ev[:, band],
                color="#1f4e9c",
                linewidth=1.1,
                zorder=3,
                label="PySCF" if band == 0 and vasp is not None else None,
            )
    else:
        for band in range(energies_ev.shape[1]):
            axis.plot(distances, energies_ev[:, band], color="0.25", linewidth=0.5, zorder=2)
        axis.scatter(
            np.repeat(distances[:, None], energies_ev.shape[1], axis=1).ravel(),
            energies_ev.ravel(),
            s=np.clip(weights.ravel(), 0.0, None) * 45.0,
            color=color,
            alpha=0.75,
            edgecolors="none",
            zorder=3,
            label=weight_label,
        )

    for tick in ticks[1:-1]:
        axis.axvline(tick, color="0.3", linewidth=0.6, zorder=0)
    for position in breaks_distance:
        axis.axvline(position, color="0.0", linewidth=1.2, zorder=0)
    axis.axhline(0.0, color="crimson", linewidth=0.8, linestyle="--", zorder=0)
    if fermi_ev is not None and abs(fermi_ev) > 1e-6:
        axis.axhline(fermi_ev, color="darkorange", linewidth=0.8, linestyle=":", zorder=0)

    axis.set_xticks(ticks)
    axis.set_xticklabels(tick_labels)
    axis.set_xlim(distances[0], distances[-1])
    axis.set_ylim(*energy_window)
    axis.set_ylabel(ylabel)
    axis.set_title(title, fontsize=10)
    axis.tick_params(direction="in", top=True, right=True)
    if vasp is not None or weight_label:
        axis.legend(loc="upper right", fontsize=8, framealpha=0.9, markerscale=2.0)
    figure.tight_layout()
    figure.savefig(output)
    plt.close(figure)


def plot_dos(output: Path, energies_ev, weights, sigma, energy_window, title, ylabel):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    grid = np.linspace(energy_window[0], energy_window[1], 1201)
    delta = grid[:, None, None] - energies_ev[None, :, :]
    gaussian = np.exp(-((delta / sigma) ** 2)) / (sigma * np.sqrt(np.pi))
    dos = 2.0 * np.einsum("gkn,k->g", gaussian, weights)  # factor 2 = spin

    figure, axis = plt.subplots(figsize=(3.4, 6.0))
    axis.plot(dos, grid, color="#1f4e9c", linewidth=1.0)
    axis.fill_betweenx(grid, 0.0, dos, color="#1f4e9c", alpha=0.2)
    axis.axhline(0.0, color="crimson", linewidth=0.8, linestyle="--")
    axis.set_ylim(*energy_window)
    axis.set_xlim(left=0.0)
    axis.set_xlabel("DOS (states / eV / cell)")
    axis.set_ylabel(ylabel)
    axis.set_title(title, fontsize=10)
    axis.tick_params(direction="in", top=True, right=True)
    figure.tight_layout()
    figure.savefig(output)
    plt.close(figure)
    return grid, dos


