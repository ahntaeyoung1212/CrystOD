def build_cell(lattice, symbols, frac, args):
    from pyscf.pbc import gto

    cell = gto.Cell()
    cell.a = lattice
    cell.atom = [(symbol, tuple(position)) for symbol, position in zip(symbols, frac @ lattice)]
    cell.unit = "Angstrom"
    cell.basis = args.basis
    if args.pseudo.lower() not in {"none", "off", "false"}:
        cell.pseudo = args.pseudo
    if args.ke_cutoff:
        cell.ke_cutoff = args.ke_cutoff
    cell.precision = args.precision
    cell.max_memory = args.max_memory
    cell.verbose = args.verbose
    if args.symmetry:
        # required by make_kpts(space_group_symmetry=True)
        cell.space_group_symmetry = True
        cell.symmorphic = False
    cell.build()
    return cell


def build_mean_field(cell, kpts, args):
    from pyscf.pbc import dft, scf

    if args.xc.lower() in {"hf", "hartree-fock"}:
        mf = scf.KRHF(cell, kpts)
        is_hybrid = True
    else:
        mf = dft.KRKS(cell, kpts)
        mf.xc = args.xc
        is_hybrid = abs(mf._numint.hybrid_coeff(mf.xc)) > 1e-10

    if is_hybrid or args.df == "gdf":
        if args.df == "fftdf" and is_hybrid:
            print(
                "NOTE: '{}' contains exact exchange; switching to Gaussian density fitting.\n"
                "      Expect this to be far more expensive, and the band step to rebuild the\n"
                "      3-centre integrals for every path k-point.".format(args.xc)
            )
        mf = mf.density_fit()

    mf.conv_tol = args.conv_tol
    mf.max_cycle = args.max_cycle
    mf.max_memory = args.max_memory
    # MINAO/atom guesses assume all-electron shell structures and crash for
    # compact GTH sets (Sc is a known case), so hcore is the safe default here.
    mf.init_guess = args.init_guess
    if args.sigma > 0:
        from pyscf.pbc.scf import addons

        mf = addons.smearing_(mf, sigma=args.sigma / HARTREE2EV, method=args.smearing)
    return mf


def compute_bands(mf, cell, kpts_band_abs, dm, chunk: int, want_coeff: bool):
    """Non-SCF diagonalisation on the path, optionally in chunks.

    One call per chunk rebuilds the density on the FFT grid from the *mesh*
    density matrix, so chunking costs a fixed overhead per call and only buys
    progress reporting; ``chunk = 0`` does the whole path in one call, which is
    both fastest and still memory-safe (PySCF sizes its grid blocks from
    ``max_memory`` and the total number of k-points).
    """
    energies: list[np.ndarray] = []
    coefficients: list[np.ndarray] = []
    total = len(kpts_band_abs)
    if not chunk:
        print(
            f"    all {total} k-points in one call"
            " (pass --band-chunk N for progress reporting)",
            flush=True,
        )
    chunk = max(1, chunk or total)
    started = time.time()
    for offset in range(0, total, chunk):
        block = kpts_band_abs[offset : offset + chunk]
        block_energy, block_coeff = mf.get_bands(block, cell=cell, dm_kpts=dm)
        energies.extend(np.asarray(e, dtype=float) for e in block_energy)
        if want_coeff:
            coefficients.extend(np.asarray(c) for c in block_coeff)
        done = min(offset + chunk, total)
        elapsed = time.time() - started
        eta = elapsed / done * (total - done)
        print(
            f"    band k-points {done:4d}/{total}  "
            f"[{elapsed:6.1f} s elapsed, ~{eta:6.1f} s left]",
            flush=True,
        )
    return np.array(energies), coefficients


def mulliken_weights(cell, kpts_band_abs, coefficients, element_groups):
    """Element-projected Mulliken weight of every band at every path k-point.

    ``w[k, n, e] = sum_{mu in element e} Re[ conj(C_mu,n) (S C)_mu,n ]``
    which sums to one over the elements for each (k, n).
    """
    overlaps = cell.pbc_intor("int1e_ovlp", hermi=1, kpts=kpts_band_abs)
    if len(kpts_band_abs) == 1 and not isinstance(overlaps, (list, tuple)):
        overlaps = [overlaps]
    n_elements = len(element_groups)
    weights = np.zeros((len(coefficients), coefficients[0].shape[1], n_elements))
    for k, (coeff, overlap) in enumerate(zip(coefficients, overlaps)):
        gross = (coeff.conj() * (overlap @ coeff)).real  # (nao, nmo)
        for e, ao_indices in enumerate(element_groups):
            weights[k, :, e] = gross[ao_indices, :].sum(axis=0)
    return weights


def ao_indices_by_element(cell, symbols):
    """AO index lists grouped by element, in first-appearance order."""
    slices = cell.aoslice_by_atom()
    elements: list[str] = []
    for symbol in symbols:
        if symbol not in elements:
            elements.append(symbol)
    groups = []
    for element in elements:
        indices: list[int] = []
        for atom, symbol in enumerate(symbols):
            if symbol == element:
                indices.extend(range(slices[atom, 2], slices[atom, 3]))
        groups.append(np.array(indices, dtype=int))
    return elements, groups


