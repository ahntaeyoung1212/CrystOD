def prettify(label: str) -> str:
    """seekpath/VASP label -> matplotlib label."""
    key = label.upper()
    if "_" in key:
        stem, _, sub = key.partition("_")
        return f"{GREEK_MPL.get(stem, stem.capitalize() if len(stem) > 1 else stem)}$_{{{sub}}}$"
    return GREEK_MPL.get(key, label)


def seekpath_reference(lattice, symbols, frac, tolerance: float):
    """Run seekpath and return (point_coords, path, primitive_lattice, sg_symbol, sg_number)."""
    try:
        import seekpath
    except ImportError:
        raise SystemExit(
            "ERROR: seekpath is required for automatic k-paths.\n"
            "       `pip install seekpath`, or give --kpoints / --path explicitly."
        )
    from pyscf.data.elements import charge

    numbers = [charge(symbol) for symbol in symbols]
    result = seekpath.get_path((lattice, frac, numbers), symprec=tolerance)
    return (
        result["point_coords"],
        result["path"],
        np.array(result["primitive_lattice"], dtype=float),
        result["spacegroup_international"],
        result["spacegroup_number"],
    )


def group_path(path: list[tuple[str, str]]) -> list[list[str]]:
    """Turn seekpath's (start, end) list into continuous label chains."""
    chains: list[list[str]] = []
    for start, end in path:
        if chains and chains[-1][-1] == start:
            chains[-1].append(end)
        else:
            chains.append([start, end])
    return chains


def interpolate_path(chains, point_coords, npoints: int):
    """Sample every leg of every chain.

    Returns ``(kpts_frac, labels, breaks)`` where ``kpts_frac`` is (N, 3) in the
    reciprocal basis, ``labels`` is a list of ``(index, label)`` for the vertices
    and ``breaks`` holds the indices at which the path is discontinuous ('|').
    """
    kpts: list[np.ndarray] = []
    labels: list[tuple[int, str]] = []
    breaks: list[int] = []
    for chain_index, chain in enumerate(chains):
        if chain_index > 0:
            breaks.append(len(kpts))
        for leg_index in range(len(chain) - 1):
            start = np.asarray(point_coords[chain[leg_index]], dtype=float)
            end = np.asarray(point_coords[chain[leg_index + 1]], dtype=float)
            leg = np.linspace(start, end, npoints)
            if leg_index > 0:
                leg = leg[1:]  # the joint is already there
            else:
                labels.append((len(kpts), chain[leg_index]))
            kpts.extend(leg)
            labels.append((len(kpts) - 1, chain[leg_index + 1]))
    return np.array(kpts), labels, breaks


def parse_vasp_kpoints(path: Path, npoints_fallback: int):
    """Read a VASP KPOINTS file and return (kpts_frac, labels, breaks, kind).

    Two layouts are understood:

    * *explicit* (``Reciprocal``/``Cartesian`` on line 3): the zero-weight lines
      are the band path, exactly as VASP treats them.  Trailing ``! K.1 Gamma -``
      comments supply the vertex labels and the ``|`` discontinuities.
    * *line mode* (``Line-mode`` on line 3): pairs of end points, each leg
      sampled with the number of points given on line 2.
    """
    lines = [line.rstrip() for line in path.read_text().splitlines()]
    stripped = [line.strip() for line in lines]
    if len(stripped) < 4:
        raise SystemExit(f"ERROR: {path} is not a KPOINTS file")

    try:
        nk_header = int(stripped[1].split()[0])
    except (ValueError, IndexError):
        nk_header = 0
    mode = stripped[2][:1].lower()

    if mode == "l":  # line mode
        per_leg = nk_header or npoints_fallback
        coord = stripped[3][:1].lower()
        if coord not in "rk":
            raise SystemExit("ERROR: only reciprocal-mode Line-mode KPOINTS are supported")
        vertices: list[tuple[np.ndarray, str]] = []
        for line in stripped[4:]:
            if not line:
                continue
            body, _, comment = line.partition("!")
            fields = body.split()
            if len(fields) < 3:
                continue
            vertices.append((np.array([float(x) for x in fields[:3]]), comment.strip()))
        if len(vertices) % 2:
            raise SystemExit("ERROR: Line-mode KPOINTS must list an even number of end points")
        chains: list[list[str]] = []
        coords: dict[str, np.ndarray] = {}

        def register(point: np.ndarray, name: str, serial: int) -> str:
            key = name or f"K{serial}"
            base, suffix = key, 1
            while key in coords and not np.allclose(coords[key], point, atol=1e-8):
                suffix += 1
                key = f"{base}'{'' if suffix == 2 else suffix}"
            coords[key] = point
            return key

        for leg in range(len(vertices) // 2):
            start_point, start_name = vertices[2 * leg]
            end_point, end_name = vertices[2 * leg + 1]
            start_key = register(start_point, start_name, 2 * leg)
            end_key = register(end_point, end_name, 2 * leg + 1)
            if chains and np.allclose(coords[chains[-1][-1]], start_point, atol=1e-8):
                chains[-1].append(end_key)
            else:
                chains.append([start_key, end_key])
        kpts, labels, breaks = interpolate_path(chains, coords, per_leg)
        return kpts, labels, breaks, "line-mode"

    if mode not in "rkc":
        raise SystemExit(
            f"ERROR: unsupported KPOINTS mode '{stripped[2]}'.\n"
            "       Use an explicit reciprocal list or Line-mode."
        )
    if mode == "c" or mode == "k":
        raise SystemExit(
            "ERROR: Cartesian explicit KPOINTS are not supported; use reciprocal coordinates."
        )

    band_kpts: list[np.ndarray] = []
    band_tags: list[str] = []
    n_weighted = 0
    for line in stripped[3:]:
        if not line:
            continue
        body, _, comment = line.partition("!")
        fields = body.split()
        if len(fields) < 4:
            continue
        try:
            values = [float(x) for x in fields[:4]]
        except ValueError:
            continue
        if values[3] != 0.0:
            n_weighted += 1
            continue
        band_kpts.append(np.array(values[:3]))
        band_tags.append(comment.strip())
    if not band_kpts:
        raise SystemExit(
            f"ERROR: {path} has no zero-weight k-points, so it contains no band path.\n"
            "       Use --path or let seekpath generate one."
        )

    labels: list[tuple[int, str]] = []
    breaks: list[int] = []
    for index, tag in enumerate(band_tags):
        if not tag:
            continue
        # "K.1 Gamma -" / "K.6 X |" / "K.8 M X"  (last field is the connector)
        fields = tag.split()
        if len(fields) >= 2 and fields[0].upper().startswith("K."):
            name = fields[1]
            connector = fields[2] if len(fields) > 2 else ""
        else:
            name = fields[0]
            connector = fields[1] if len(fields) > 1 else ""
        labels.append((index, name))
        if connector == "|":
            breaks.append(index + 1)
    if n_weighted:
        print(
            f"NOTE: {path.name} also holds {n_weighted} weighted k-points (the VASP SCF mesh);\n"
            "      PySCF regenerates that mesh itself, so only the zero-weight path is used."
        )
    return np.array(band_kpts), labels, breaks, "explicit zero-weight"


def path_distances(kpts_frac: np.ndarray, recip: np.ndarray, breaks: list[int]) -> np.ndarray:
    """Cumulative |Delta k| along the path, frozen across '|' discontinuities."""
    cartesian = kpts_frac @ recip
    steps = np.linalg.norm(np.diff(cartesian, axis=0), axis=1)
    for index in breaks:
        if 0 < index <= len(steps):
            steps[index - 1] = 0.0
    return np.concatenate([[0.0], np.cumsum(steps)])


def merge_ticks(labels, distances, breaks):
    """Collapse coincident vertices into single ticks, joining them with '|'."""
    ticks: list[float] = []
    tick_labels: list[str] = []
    for index, name in labels:
        position = float(distances[index])
        text = prettify(name)
        if ticks and abs(position - ticks[-1]) < 1e-8:
            if tick_labels[-1] != text:
                tick_labels[-1] = f"{tick_labels[-1]}|{text}"
            continue
        ticks.append(position)
        tick_labels.append(text)
    return ticks, tick_labels


