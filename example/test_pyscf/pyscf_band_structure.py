def band_edges(mesh_energies, path_energies, mesh_kpts_frac, path_kpts_frac, nocc):
    """VBM/CBM over the union of the SCF mesh and the path, as VASP reports them."""
    nband = min(mesh_energies.shape[1], path_energies.shape[1])
    all_energies = np.vstack([mesh_energies[:, :nband], path_energies[:, :nband]])
    all_kpts = np.vstack([mesh_kpts_frac, path_kpts_frac])
    homo_index = int(np.argmax(all_energies[:, nocc - 1]))
    vbm = float(all_energies[homo_index, nocc - 1])
    if nocc >= all_energies.shape[1]:
        return vbm, None, None, None, all_kpts[homo_index], None
    lumo_index = int(np.argmin(all_energies[:, nocc]))
    cbm = float(all_energies[lumo_index, nocc])
    direct_gaps = all_energies[:, nocc] - all_energies[:, nocc - 1]
    direct_index = int(np.argmin(direct_gaps))
    return (
        vbm,
        cbm,
        float(cbm - vbm),
        float(direct_gaps[direct_index]),
        all_kpts[homo_index],
        (all_kpts[lumo_index], all_kpts[direct_index]),
    )


def read_eigenval(path: Path):
    """Parse a VASP EIGENVAL file.

    Returns ``(kpts_frac, weights, energies, occupations, nelect)``.  For
    ISPIN = 2 the two spin channels are concatenated along the band axis, which
    is all an overlay plot needs.
    """
    tokens = path.read_text().splitlines()
    ispin = int(tokens[0].split()[3])
    nelect, nkpts, nbands = (int(x) for x in tokens[5].split()[:3])
    kpts, weights, energies, occupations = [], [], [], []
    index = 6
    for _ in range(nkpts):
        while index < len(tokens) and not tokens[index].strip():
            index += 1
        fields = tokens[index].split()
        kpts.append([float(x) for x in fields[:3]])
        weights.append(float(fields[3]))
        index += 1
        block_energy, block_occupation = [], []
        for _ in range(nbands):
            values = [float(x) for x in tokens[index].split()[1:]]
            block_energy.extend(values[:ispin])
            block_occupation.extend(values[ispin : 2 * ispin])
            index += 1
        energies.append(block_energy)
        occupations.append(block_occupation)
    return (
        np.array(kpts),
        np.array(weights),
        np.array(energies),
        np.array(occupations),
        nelect,
    )


